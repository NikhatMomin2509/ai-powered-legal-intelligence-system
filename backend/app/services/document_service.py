logger = logging.getLogger("legal_ai.document_service")

DOCUMENT_TYPE_KEYWORDS = {
    "Rental/Lease Agreement": ["lessor", "lessee", "tenant", "landlord", "rent", "lease"],
    "Employment Contract": ["employee", "employer", "salary", "designation", "probation"],
    "Service Agreement": ["service provider", "scope of services", "deliverables"],
    "NDA": ["non-disclosure", "confidential information", "nda"],
    "Loan Agreement": ["borrower", "lender", "principal amount", "repayment"],
    "General Contract": ["witnesseth", "party of the first part", "in consideration of"],
}

DOCUMENT_ANALYSIS_DISCLAIMER = (
    "This is an AI-generated, informational risk analysis of the uploaded document. "
    "Risk flags are produced by rule-based keyword matching, not a trained legal "
    "classifier, and may miss risks or flag clauses that are not actually problematic "
    "in context. Explanations are generated by a language model grounded only in "
    "retrieved statutory text where available, and the system does not fabricate legal "
    "citations. This is NOT legal advice, does not guarantee identification of every "
    "risk, and is not a substitute for review by a qualified advocate."
)


def classify_document_type(full_text: str) -> str:
    text_lower = full_text.lower()
    scores = {doc_type: sum(1 for kw in kws if kw in text_lower)
              for doc_type, kws in DOCUMENT_TYPE_KEYWORDS.items()}
    best_type = max(scores, key=scores.get)
    return best_type if scores[best_type] > 0 else "Unknown"


def save_uploaded_file(contents: bytes, document_id: str, original_filename: str) -> Path:
    UPLOAD_DIR.mkdir(parents=True, exist_ok=True)
    extension = Path(original_filename).suffix.lower()
    dest_path = UPLOAD_DIR / f"{document_id}{extension}"
    with open(dest_path, "wb") as f:
        f.write(contents)
    return dest_path


def create_document_record(db: Session, document_id: str, filename: str, file_path: str) -> DocumentAnalysis:
    record = DocumentAnalysis(
        document_id=document_id,
        filename=filename,
        file_path=file_path,
        status="uploaded",
    )
    db.add(record)
    db.commit()
    db.refresh(record)
    return record


def _retrieve_laws_for_clause(clause_text: str) -> list:
    """Reuses the EXISTING shared RAG engine. Returns [] (not an error) if
    the RAG engine is unavailable — a missing index shouldn't crash the
    whole document analysis, just mean that clause gets no legal citations."""
    try:
        hits = hybrid_retrieve_laws(clause_text[:300], top_k=3)
        return [
            {
                "act": doc.metadata.get("act"),
                "section": doc.metadata.get("section"),
                "title": doc.metadata.get("title"),
                "content": doc.page_content,
            }
            for doc, score, method in hits
        ]
    except RAGEngineError as e:
        logger.warning("RAG retrieval unavailable for a clause explanation: %s", e)
        return []


def _explain_clause_with_llm(clause_text: str, risk_category: str, retrieved_laws: list) -> dict:
    """Same grounding discipline as issue_analyzer.py: cite retrieved laws
    by ref_id only, never invent one, say so explicitly if nothing relevant
    was retrieved. A per-clause LLM failure is caught here and returns a
    clear placeholder rather than failing the entire document analysis."""
    law_lines = [
        f"[L{i}] {law['act']} Section {law['section']} — {law['title']}\n    {law['content'][:500]}"
        for i, law in enumerate(retrieved_laws, start=1)
    ]
    law_block = "\n\n".join(law_lines) if law_lines else "(no relevant law retrieved for this clause)"

    system_prompt = f"""You are a legal-document assistant explaining one clause from a contract.

CLAUSE TEXT:
{clause_text[:1500]}

FLAGGED RISK CATEGORY (rule-based keyword match, not a legal determination): {risk_category}

RETRIEVED LAWS:
{law_block}

INSTRUCTIONS:
- Explain this clause in plain, non-legal English (2-3 sentences).
- Explain briefly why this TYPE of clause can be risky for the party agreeing to it.
- If a retrieved law is genuinely relevant, cite it ONLY by its ref_id (e.g. "L1"). Do NOT
  invent a law or cite one not listed above. If none are relevant, say so explicitly.
- Suggest ONE concrete, practical negotiation point for this clause.
- Do not claim legal certainty — this is informational only.

Respond with ONLY a JSON object, no other text:
{{"plain_explanation": "...", "why_risky": "...", "relevant_law_ref_ids": ["L1"], "negotiation_point": "..."}}
"""
    try:
        raw = call_llm(system_prompt, "Produce the JSON now.", max_tokens=600, reasoning_effort="low")
        parsed = _extract_json(raw)
    except Exception as e:
        logger.warning("Clause explanation LLM call failed: %s", e)
        parsed = {
            "plain_explanation": None,
            "why_risky": None,
            "relevant_law_ref_ids": [],
            "negotiation_point": None,
            "llm_error": "An explanation could not be generated for this clause.",
        }

    by_ref = {f"L{i}": law for i, law in enumerate(retrieved_laws, start=1)}
    cited_laws = [by_ref[rid] for rid in parsed.get("relevant_law_ref_ids", []) if rid in by_ref]
    parsed["relevant_laws"] = cited_laws
    parsed.pop("relevant_law_ref_ids", None)
    return parsed


def analyze_document(db: Session, document_id: str) -> dict:
    record = db.query(DocumentAnalysis).filter(DocumentAnalysis.document_id == document_id).first()
    if record is None:
        raise ValueError(f"No document found with document_id={document_id}")

    file_extension = Path(record.file_path).suffix
    extraction = extract_text(record.file_path, file_extension)

    document_type = classify_document_type(extraction.full_text)
    clauses = segment_clauses(extraction.pages)
    flagged = detect_risks(clauses)
    risk_score, risk_level = calculate_risk_score(flagged)

    risky_clauses_output = []
    for flag in flagged:
        retrieved_laws = _retrieve_laws_for_clause(flag.clause_text)
        explanation = _explain_clause_with_llm(flag.clause_text, flag.risk_category, retrieved_laws)
        risky_clauses_output.append({
            "clause_id": flag.clause_id,
            "page_number": flag.page_number,
            "risk_level": flag.risk_level,
            "risk_category": flag.risk_category,
            "clause_text": flag.clause_text,
            "reason": flag.reason,
            **explanation,
        })

    negotiation_points = [c["negotiation_point"] for c in risky_clauses_output if c.get("negotiation_point")]

    summary = (
        f"{len(flagged)} potentially risky clause(s) flagged out of {len(clauses)} segmented clauses. "
        f"Overall risk level: {risk_level} ({risk_score}/100)."
    )

    full_result = {
        "document_id": document_id,
        "document_type": document_type,
        "risk_score": risk_score,
        "risk_level": risk_level,
        "total_clauses_segmented": len(clauses),
        "risky_clauses": risky_clauses_output,
        "summary": summary,
        "negotiation_points": negotiation_points,
        "ocr_warning": extraction.ocr_warning,
        "disclaimer": DOCUMENT_ANALYSIS_DISCLAIMER,
    }

    record.document_type = document_type
    record.status = "analyzed"
    record.risk_score = risk_score
    record.risk_level = risk_level
    record.extracted_text_preview = extraction.full_text[:1000]
    record.full_result = full_result
    db.commit()

    return full_result
