# 2. Capture UI Screenshots at 1440 px and 390 px
print("\nCapturing UI Screenshots at 1440 px and 390 px...")
with sync_playwright() as p:
    browser = p.chromium.launch()

    # Desktop 1440px
    ctx_desktop = browser.new_context(viewport={"width": 1440, "height": 900})
    page_d = ctx_desktop.new_page()
    page_d.goto("http://localhost:5173/issue-analyzer", wait_until="networkidle")
    page_d.fill("textarea", "My landlord is withholding my security deposit claiming normal painting wear and tear costs.")
    page_d.click("button:has-text('Analyze issue')")
    page_d.wait_for_selector("text=One-time anonymous analysis.", timeout=20000)
    page_d.screenshot(path=os.path.join(SHOTS_DIR, "ui_issue_analyzer_1440px.png"), full_page=True)
    print("Saved ui_issue_analyzer_1440px.png")

    page_d.goto("http://localhost:5173/history", wait_until="networkidle")
    page_d.screenshot(path=os.path.join(SHOTS_DIR, "ui_history_1440px.png"))
    print("Saved ui_history_1440px.png")

    # Mobile 390px (iPhone 12/13/14 viewport)
    ctx_mobile = browser.new_context(
        viewport={"width": 390, "height": 844},
        user_agent="Mozilla/5.0 (iPhone; CPU iPhone OS 16_0 like Mac OS X) AppleWebKit/605.1.15",
        is_mobile=True
    )
    page_m = ctx_mobile.new_page()
    page_m.goto("http://localhost:5173/issue-analyzer", wait_until="networkidle")
    page_m.screenshot(path=os.path.join(SHOTS_DIR, "ui_issue_analyzer_390px_initial.png"))
    print("Saved ui_issue_analyzer_390px_initial.png")

    page_m.fill("textarea", "My landlord is withholding my security deposit claiming normal painting wear and tear costs.")
    page_m.click("button:has-text('Analyze issue')")
    page_m.wait_for_selector("text=One-time anonymous analysis.", timeout=20000)
    page_m.screenshot(path=os.path.join(SHOTS_DIR, "ui_issue_analyzer_390px_result.png"))
    print("Saved ui_issue_analyzer_390px_result.png")

    browser.close()

print("\nVisual artifact generation complete!")
