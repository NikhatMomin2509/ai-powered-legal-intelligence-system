"""
generate_visual_artifacts.py — Generates visual assets:
1. Rasterizes sample PDFs (issue, case, document) into PNG images using PyMuPDF.
2. Takes UI screenshots at 1440 px and 390 px (responsive mobile view) using Playwright.
"""

import os
import pymupdf
from playwright.sync_api import sync_playwright

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
SHOTS_DIR = os.path.join(BASE_DIR, "screenshots")
os.makedirs(SHOTS_DIR, exist_ok=True)

# 1. Rasterize sample PDFs
case_pdf_path = os.path.join(SHOTS_DIR, "test_downloaded_case.pdf")
doc_pdf_path = os.path.join(SHOTS_DIR, "test_downloaded_document.pdf")

def rasterize_pdf(pdf_path, prefix):
    if not os.path.exists(pdf_path):
        print(f"Skipping {pdf_path}: not found")
        return []
    doc = pymupdf.open(pdf_path)
    imgs = []
    for page_num in range(len(doc)):
        page = doc[page_num]
        pix = page.get_pixmap(dpi=150)
        out_name = f"{prefix}_page_{page_num + 1}.png"
        out_path = os.path.join(SHOTS_DIR, out_name)
        pix.save(out_path)
        imgs.append(out_path)
        print(f"Rasterized: {out_path}")
    return imgs

print("Rasterizing PDFs...")
rasterize_pdf(case_pdf_path, "pdf_case_report")
rasterize_pdf(doc_pdf_path, "pdf_document_report")

